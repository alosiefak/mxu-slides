#!/usr/bin/env node
// Generates the C# document models for the Windows app from the shared
// schema in packages/schema/documents.json, mirroring packages/schema/codegen.mjs
// (which generates the Swift models for the Mac app). Field names, optionality
// and enum raw values match the Mac app exactly, so documents are
// interchangeable between the two.
//
// Usage (from the repository root or anywhere):
//   node apps/windows/tools/codegen-csharp.mjs          write Models.g.cs
//   node apps/windows/tools/codegen-csharp.mjs --check  exit 1 if it is stale

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..', '..')
const schemaPath = join(repoRoot, 'packages', 'schema', 'documents.json')
const outPath = join(here, '..', 'src', 'MxU.Slides.Core', 'Generated', 'Models.cs')
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1)

function csType(t) {
  if (t.startsWith('list:')) return `List<${csType(t.slice(5))}>`
  return { string: 'string', int: 'int', double: 'double', bool: 'bool' }[t] ?? t
}

function isValueType(t) {
  if (['int', 'double', 'bool'].includes(t)) return true
  return schema.types[t]?.kind === 'enum'
}

function defaultValue(t) {
  if (t.startsWith('list:')) return 'new()'
  if (t === 'string') return '""'
  if (['int', 'double', 'bool'].includes(t)) return null
  const def = schema.types[t]
  if (!def) throw new Error(`Unknown type ${t}`)
  if (def.kind === 'enum') return null
  return 'new()'
}

function emit() {
  let out = ''
  out += '// <auto-generated>\n'
  out += '// Generated by apps/windows/tools/codegen-csharp.mjs from packages/schema/documents.json.\n'
  out += '// Do not edit by hand: edit the schema and re-run the generator.\n'
  out += '// </auto-generated>\n'
  out += '#nullable enable\n'
  out += 'using System;\n'
  out += 'using System.Collections.Generic;\n'
  out += 'using System.Text.Json;\n'
  out += 'using System.Text.Json.Serialization;\n\n'
  out += 'namespace MxU.Slides.Core.Model;\n\n'
  out += 'public static partial class SchemaInfo\n{\n'
  out += `    public const int SchemaVersion = ${schema.schemaVersion};\n}\n`

  for (const [name, def] of Object.entries(schema.types)) {
    out += '\n'
    if (def.kind === 'enum') {
      out += `[JsonConverter(typeof(${name}JsonConverter))]\n`
      out += `public enum ${name}\n{\n`
      for (const c of def.cases) out += `    ${pascal(c)},\n`
      out += '}\n\n'
      out += `public sealed class ${name}JsonConverter : JsonConverter<${name}>\n{\n`
      out += `    public static string ToRaw(${name} value) => value switch\n    {\n`
      for (const c of def.cases) out += `        ${name}.${pascal(c)} => "${c}",\n`
      out += `        _ => throw new JsonException($"Unknown ${name} value: {value}"),\n    };\n\n`
      out += `    public static bool TryParse(string? raw, out ${name} value)\n    {\n`
      out += '        switch (raw)\n        {\n'
      for (const c of def.cases) out += `            case "${c}": value = ${name}.${pascal(c)}; return true;\n`
      for (const [legacy, current] of Object.entries(def.legacyAliases ?? {})) {
        out += `            case "${legacy}": value = ${name}.${pascal(current)}; return true;\n`
      }
      out += '            default: value = default; return false;\n        }\n    }\n\n'
      out += `    public override ${name} Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)\n    {\n`
      out += '        var raw = reader.GetString();\n'
      out += `        return TryParse(raw, out var value) ? value : throw new JsonException($"Unknown ${name} value: {raw}");\n    }\n\n`
      out += `    public override void Write(Utf8JsonWriter writer, ${name} value, JsonSerializerOptions options) =>\n`
      out += '        writer.WriteStringValue(ToRaw(value));\n}\n'
    } else if (def.kind === 'record') {
      out += `public sealed partial class ${name}\n{\n`
      for (const f of def.fields) {
        let prop = pascal(f.name)
        if (prop === name) prop += 'Value'
        const type = csType(f.type) + (f.optional ? '?' : '')
        const attrs = [`JsonPropertyName("${f.name}")`]
        if (!f.optional) attrs.push('JsonRequired')
        let line = `    [${attrs.join(', ')}]\n    public ${type} ${prop} { get; set; }`
        if (!f.optional) {
          const d = defaultValue(f.type)
          if (d) line += ` = ${d};`
        }
        out += line + '\n'
      }
      out += '}\n'
    } else {
      throw new Error(`Unknown kind ${def.kind} for ${name}`)
    }
  }
  return out.replace(/\n/g, '\r\n')
}

const generated = emit()
if (process.argv.includes('--check')) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : ''
  if (current.replace(/\r\n/g, '\n') !== generated.replace(/\r\n/g, '\n')) {
    console.error(`${outPath} is out of date with ${schemaPath}. Run: node apps/windows/tools/codegen-csharp.mjs`)
    process.exit(1)
  }
  console.log('C# models are up to date with the schema.')
} else {
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, generated)
  console.log(`Wrote ${outPath}`)
}
